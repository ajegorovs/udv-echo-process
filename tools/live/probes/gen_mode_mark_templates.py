"""Regenerate ``acquire/mode_marks_templates.py`` from the committed measured fixtures.

Run from the repository root::

    python tools/live/probes/gen_mode_mark_templates.py

The fixtures in ``tests/data/mpx-mode/`` are the operator's real captured popup crops, copied
and renamed so the report vocabulary carries no machine identity. Nothing here synthesises a
raster: :func:`udv_echo_process.acquire.mode_marks.build_templates` learns each one from its
own frame, exactly as ``tests/test_acquire_mpx_mode_marks.py`` re-derives it.
"""

from __future__ import annotations

import pprint
import subprocess
from pathlib import Path

from udv_echo_process.acquire import mode_marks

ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / "tests" / "data" / "mpx-mode"
TARGET = ROOT / "src" / "udv_echo_process" / "acquire" / "mode_marks_templates.py"

LABELS = {
    "ENABLE_MULTIPLEXER": (
        DATA / "disabled-rolling-on" / "channels-roi-frame-1.png",
        mode_marks.SETTINGS_FULL,
    ),
    "DESABLE_MULTIPLEXER": (
        DATA / "entry-clipped-enabled" / "channels-roi-frame-1.png",
        mode_marks.MULTIPLEXER_ON_ENTRY,
    ),
}
MARKS = {
    "GREEN_CHECK": (
        DATA / "disabled-rolling-on" / "channels-roi-frame-1.png",
        "green-check",
        mode_marks.GREEN_INK,
    ),
    "RED_CROSS": (
        DATA / "disabled-rolling-off" / "channels-roi-frame-1.png",
        "red-cross",
        mode_marks.ROLLOVER_INK,
    ),
}


def main() -> None:
    templates = mode_marks.build_templates(LABELS, MARKS)
    lines = [
        '"""Committed rasters for the MPX mode entry and its rollover mark.',
        "",
        "Generated by ``tools/live/probes/gen_mode_mark_templates.py`` from the measured",
        "fixtures in ``tests/data/mpx-mode/`` (real operator captures, renamed only); do not",
        "edit by hand. Each row string is one exact ink bitmap at the measured box or rect, so",
        "a shifted mark or a translated caption has no entry here.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import NamedTuple",
        "",
        "",
        "class _Label(NamedTuple):",
        "    label: str",
        "    rows: tuple[str, ...]",
        "    box: tuple[int, int, int, int]",
        "    ink: int",
        "    source: str",
        "    source_digest: str",
        "",
        "",
        "class _Mark(NamedTuple):",
        "    mark: str",
        "    rows: tuple[str, ...]",
        "    allow: str",
        "    ink: int",
        "    source: str",
        "    source_digest: str",
        "",
        "",
        "LABELS: tuple[_Label, ...] = (",
    ]
    for label, rows, box, ink, source, digest in (
        (t.label, t.rows, t.box, t.ink, t.source, t.source_digest)
        for t in templates.labels
    ):
        lines.append("    _Label(")
        lines.append(f"        label={label!r},")
        lines.append("        rows=(")
        for row in rows:
            lines.append(f"            {row!r},")
        lines.append("        ),")
        lines.append(f"        box={box!r},")
        lines.append(f"        ink={ink},")
        lines.append(f"        source={source!r},")
        lines.append(f"        source_digest={digest!r},")
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    lines.append("MARKS: tuple[_Mark, ...] = (")
    for mark, rows, allow, ink, source, digest in (
        (t.mark, t.rows, t.allow, t.ink, t.source, t.source_digest)
        for t in templates.marks
    ):
        lines.append("    _Mark(")
        lines.append(f"        mark={mark!r},")
        lines.append("        rows=(")
        for row in rows:
            lines.append(f"            {row!r},")
        lines.append("        ),")
        lines.append(f"        allow={allow!r},")
        lines.append(f"        ink={ink},")
        lines.append(f"        source={source!r},")
        lines.append(f"        source_digest={digest!r},")
        lines.append("    ),")
    lines.append(")")
    lines.append("")
    lines.append(
        "SOURCES: tuple[tuple[str, str], ...] = " + pprint.pformat(templates.sources)
    )
    lines.append("")
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    # Keep the generated file in the repository's own format, so a regeneration never shows up
    # as a formatting-only diff in review.
    ruff = ROOT / ".venv" / "Scripts" / "ruff.exe"
    if ruff.exists():
        subprocess.run([str(ruff), "format", str(TARGET)], check=True, cwd=ROOT)
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
